"""Append the moves listed in data/new_moves.json after the native 354.

IDs follow the JSON order starting at 355 and must never be reordered: saves store move IDs.
Numbers, type, category, target and flags come from the pinned PokeAPI snapshot; the JSON picks
the engine effect, the reused animation, the 12-character name and the EN/PT descriptions.
Every generated block sits between markers, so the script can be re-run safely.
"""
from pathlib import Path
import csv,json,re
ROOT=Path(__file__).resolve().parents[1];SRC=ROOT/'data/upstream/pokeapi';GAME=ROOT/'game'
FIRST_ID=355
BEGIN,END='Generated by scripts/import_new_moves.py','End of generated moves'
def rows(name):return list(csv.DictReader((SRC/(name+'.csv')).open(encoding='utf-8')))
spec=json.loads((ROOT/'data/new_moves.json').read_text(encoding='utf-8'))['moves']
pokeapi={r['identifier'].replace('-','_').upper():r for r in rows('moves')}
types={r['id']:'TYPE_'+r['identifier'].upper() for r in rows('types')}
flags={}
for r in rows('move_flag_map'):flags.setdefault(r['move_id'],set()).add(int(r['move_flag_id']))
TARGET={'10':'MOVE_TARGET_SELECTED','11':'MOVE_TARGET_BOTH','9':'MOVE_TARGET_FOES_AND_ALLY','7':'MOVE_TARGET_USER','8':'MOVE_TARGET_RANDOM',
        '1':'MOVE_TARGET_DEPENDS','6':'MOVE_TARGET_OPPONENTS_FIELD','4':'MOVE_TARGET_USER','12':'MOVE_TARGET_USER','13':'MOVE_TARGET_USER','15':'MOVE_TARGET_USER','5':'MOVE_TARGET_USER'}
CATEGORY={'1':'MOVE_CATEGORY_STATUS','2':'MOVE_CATEGORY_PHYSICAL','3':'MOVE_CATEGORY_SPECIAL'}
# Effects whose secondary effect is guaranteed or not chance-based keep the native convention.
NO_CHANCE={'EFFECT_HIT','EFFECT_QUICK_ATTACK','EFFECT_HIGH_CRITICAL','EFFECT_ALWAYS_HIT','EFFECT_DOUBLE_EDGE','EFFECT_RECOIL','EFFECT_DOUBLE_HIT',
           'EFFECT_ABSORB','EFFECT_RECHARGE','EFFECT_BRICK_BREAK','EFFECT_SOLAR_BEAM','EFFECT_LOW_KICK','EFFECT_REVENGE',
           'EFFECT_DEF_SPDEF_DOWN_HIT','EFFECT_SPEED_DOWN_USER_HIT','EFFECT_RECOIL_50','EFFECT_ALWAYS_CRIT','EFFECT_TRICK',
           'EFFECT_U_TURN','EFFECT_DRAGON_TAIL','EFFECT_FEINT','EFFECT_SUCKER_PUNCH','EFFECT_CLEAR_SMOG','EFFECT_POLLEN_PUFF',
           'EFFECT_METEOR_BEAM','EFFECT_FELL_STINGER','EFFECT_STEEL_BEAM','EFFECT_FINAL_GAMBIT','EFFECT_METAL_BURST','EFFECT_TRIPLE_AXEL','EFFECT_RECOIL_IF_MISS',
           'EFFECT_FIELD_EFFECT','EFFECT_ICE_SPINNER','EFFECT_EXPLOSION','EFFECT_SET_HAZARD','EFFECT_DEFOG','EFFECT_MODERN_MISC'}
FLINCHING={'EFFECT_FLINCH_HIT'}
def camel(key):return ''.join(part.capitalize() for part in key.split('_'))
def c_string(text):return json.dumps(text,ensure_ascii=False)
entries=[];names=[];descs=[];pointers=[];anims=[];defines=[]
for index,(key,move) in enumerate(spec.items()):
 row=pokeapi[key];move_id=FIRST_ID+index;power=int(row['power'] or 0);status=row['damage_class_id']=='1'
 if not power and not status:power=1  # native sentinel for variable/fixed damage
 effect=move['effect'];chance=0 if effect in NO_CHANCE or status else int(move.get('chance',row['effect_chance']) or 0)
 if effect=='EFFECT_OVERHEAT':chance=100
 # The pinned snapshot has no flags for the newest moves; the JSON lists them (PokeAPI flag ids).
 f=set(move['flags']) if 'flags' in move else flags.get(row['id'],set());out=[]
 if 1 in f:out.append('FLAG_MAKES_CONTACT')
 if 4 in f:out.append('FLAG_PROTECT_AFFECTED')
 if 5 in f:out.append('FLAG_MAGIC_COAT_AFFECTED')
 if 6 in f:out.append('FLAG_SNATCH_AFFECTED')
 if 7 in f:out.append('FLAG_MIRROR_MOVE_AFFECTED')
 if 9 in f:out.append('FLAG_SOUND')
 if power and effect not in FLINCHING:out.append('FLAG_KINGS_ROCK_AFFECTED')
 defines.append(f'#define MOVE_{key} {move_id}')
 entries.append(f'''    [MOVE_{key}] =
    {{
        .effect = {effect},
        .power = {power},
        .type = {types[row['type_id']]},
        .accuracy = {int(row['accuracy'] or 0)},
        .pp = {int(row['pp'])},
        .secondaryEffectChance = {chance},
        .target = {TARGET[row['target_id']]},
        .priority = {int(row['priority'])},
        .flags = {' | '.join(out) or '0'},
        .category = {CATEGORY[row['damage_class_id']]},
    }},''')
 assert len(move['name'])<=12,key
 names.append(f'    [MOVE_{key}] = _("{move["name"]}"),')
 descs.append(f'const u8 gMoveDescription_{camel(key)}[] = _({c_string(move["en"])});')
 pointers.append(f'    [MOVE_{key} - 1] = gMoveDescription_{camel(key)},')
 anims.append(f'\t.4byte Move_{move["anim"]}')
count=FIRST_ID+len(spec)
def block(lines,comment):return f'{comment} {BEGIN}\n'+'\n'.join(lines)+f'\n{comment} {END}\n'
def strip(text,comment):return re.sub(re.escape(comment+' '+BEGIN)+r'\n.*?'+re.escape(comment+' '+END)+r'\n','',text,flags=re.S)
def write(path,fn):
 p=GAME/path;text=p.read_text(encoding='utf-8');new=fn(text);p.write_text(new,encoding='utf-8')
def moves_h(t):
 t=strip(t,'//');anchor='#define MOVE_PSYCHO_BOOST 354\n'
 t=t.replace(anchor,anchor+block(defines,'//'),1)
 return re.sub(r'#define MOVES_COUNT \d+',f'#define MOVES_COUNT {count}',t,count=1)
def battle_moves(t):
 t=strip(t,'//');assert t.rstrip().endswith('};')
 return t.rstrip()[:-2]+block(entries,'//')+'};\n'
def move_names(t):
 t=strip(t,'//').replace('[MOVE_PSYCHO_BOOST]  = _("PSYCHO BOOST")\n','[MOVE_PSYCHO_BOOST]  = _("PSYCHO BOOST"),\n')
 assert t.rstrip().endswith('};');return t.rstrip()[:-2]+block(names,'//')+'};\n'
def move_desc(t):
 t=strip(strip(t,'//'),'// pointers')
 anchor='const u8 *const gMoveDescriptionPointers[MOVES_COUNT - 1] = {'
 t=t.replace(anchor,block(descs,'//')+'\n'+anchor,1)
 assert t.rstrip().endswith('};');return t.rstrip()[:-2]+block(pointers,'// pointers')+'};\n'
def anims_s(t):
 t=strip(t,'@');anchor='\t.4byte Move_PSYCHO_BOOST\n'
 return t.replace(anchor,anchor+block(anims,'@'),1)
write('include/constants/moves.h',moves_h)
write('src/data/battle_moves.h',battle_moves)
write('src/data/text/move_names.h',move_names)
write('src/move_descriptions.c',move_desc)
write('data/battle_anim_scripts.s',anims_s)
pt_path=ROOT/'data/localization/move_descriptions_ptbr.json';pt=json.loads(pt_path.read_text(encoding='utf-8'))
for key,move in spec.items():pt[camel(key)]=move['pt']
pt_path.write_text(json.dumps(pt,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Generated {len(spec)} moves ({FIRST_ID}-{count-1}); MOVES_COUNT = {count}')
